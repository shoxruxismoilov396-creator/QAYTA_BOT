@app.route("/order/<int:order_id>/status", methods=["POST"])
@login_required
def update_status(order_id):

    new_status = request.form.get("status", "")

    if new_status not in STATUSES:
        abort(400)

    with get_db() as conn:

        cur = conn.execute(
            """
            UPDATE orders
            SET status = %s
            WHERE id = %s
            """,
            (new_status, order_id)
        )

        if cur.rowcount == 0:
            abort(404)

    flash(
        f"Buyurtma №{order_id} holati yangilandi.",
        "success"
    )

    return redirect(
        url_for(
            "dashboard",
            q=request.args.get("q", ""),
            status=request.args.get("filter", "")
        )
    )


