
import os
from functools import wraps

import psycopg
from psycopg.rows import dict_row

from flask import (
    Flask,
    render_template,
    request,
    redirect,
    url_for,
    session,
    flash,
    abort
)

# ==============================
# SOZLAMALAR
# ==============================

app = Flask(__name__)

app.secret_key = os.getenv("SECRET_KEY", "").strip()

if not app.secret_key:
    raise RuntimeError("SECRET_KEY sozlanmagan!")

ADMIN_USERNAME = os.getenv("ADMIN_USERNAME", "admin").strip()
ADMIN_PASSWORD = os.getenv("ADMIN_PASSWORD", "").strip()
DATABASE_URL = os.getenv("DATABASE_URL", "").strip()

if not ADMIN_PASSWORD:
    raise RuntimeError("ADMIN_PASSWORD sozlanmagan!")

if not DATABASE_URL:
    raise RuntimeError("DATABASE_URL sozlanmagan!")

STATUSES = [
    "Yangi",
    "Qabul qilindi",
    "Jarayonda",
    "Yakunlandi",
    "Bekor qilindi"
]


# ==============================
# POSTGRESQL BAZA
# ==============================

def get_db():
    return psycopg.connect(
        DATABASE_URL,
        row_factory=dict_row,
        connect_timeout=15
    )


def init_db():
    with get_db() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS orders (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT,
                username TEXT,
                item_type TEXT,
                weight TEXT,
                address TEXT,
                phone TEXT,
                photo_id TEXT,
                status TEXT DEFAULT 'Yangi'
            )
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS
            idx_orders_user_id ON orders(user_id)
        """)


