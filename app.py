@app.route("/")
@login_required
def dashboard():

    search = request.args.get("q", "").strip()
    status = request.args.get("status", "").strip()

    query = "SELECT * FROM orders WHERE 1=1"
    params = []

    if search:

        like = f"%{search}%"

        query += """
            AND (
                CAST(id AS TEXT) ILIKE %s
                OR username ILIKE %s
                OR item_type ILIKE %s
                OR phone ILIKE %s
                OR address ILIKE %s
            )
        """

        params.extend([
            like,
            like,
            like,
            like,
            like
        ])

    if status in STATUSES:

        query += " AND status = %s"
        params.append(status)

    query += " ORDER BY id DESC LIMIT 300"

    with get_db() as conn:

        orders = conn.execute(
            query,
            params
        ).fetchall()

        total = conn.execute(
            "SELECT COUNT(*) AS count FROM orders"
        ).fetchone()["count"]

        new_count = conn.execute(
            "SELECT COUNT(*) AS count FROM orders WHERE status = %s",
            ("Yangi",)
        ).fetchone()["count"]

        progress_count = conn.execute(
            """
            SELECT COUNT(*) AS count
            FROM orders
            WHERE status IN (%s, %s)
            """,
            ("Qabul qilindi", "Jarayonda")
        ).fetchone()["count"]

        done_count = conn.execute(
            "SELECT COUNT(*) AS count FROM orders WHERE status = %s",
            ("Yakunlandi",)
        ).fetchone()["count"]

    return render_template(
        "dashboard.html",
        orders=orders,
        statuses=STATUSES,
        selected_status=status,
        search=search,
        total=total,
        new_count=new_count,
        progress_count=progress_count,
        done_count=done_count
    )


